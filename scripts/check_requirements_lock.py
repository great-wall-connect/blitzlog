#!/usr/bin/env python3
"""Fail if the hash-pinned lambda requirements locks have drifted from the
dependency graph their `.in` sources declare.

Why this check exists
---------------------
`lambda/requirements-{aws,alicloud}.txt` are pip-compile locks that carry
a `--hash` on every requirement, so pip installs them in `--require-hashes`
mode: every transitive dependency must be pinned with `==` or the install
aborts outright.

Those locks target the Lambda runtime's Python (3.12 — see
`runtime = "python3.12"` in infra/aws/modules/core/lambda.tf). Dependabot
recompiles them under Python >= 3.13, where `aiohttp`'s
`typing_extensions>=4.4; python_version < "3.13"` marker is false, so
pip-compile concludes the dependency is unnecessary and DROPS the pin. The
lock then stops installing at all, with an error that says nothing about
Python versions:

    ERROR: In --require-hashes mode, all requirements must have their
    versions pinned with ==. These do not:
        typing_extensions>=4.4 ... (from aiohttp==3.14.5)

That broke the `Lint + test (Python)` job on PRs #159 and #180, and would
have shipped an alicloud Lambda bundle with no `typing_extensions` in it.

This check re-resolves each `.in` under the lock's own target Python and
compares the resulting `name==version` set against the committed lock. A
mismatch means the lock no longer describes the graph its source declares.

Usage:
    python scripts/check_requirements_lock.py

Requires `pip-tools` importable by the running interpreter, and that
interpreter must be the Python the lock was compiled for (pip-compile
evaluates environment markers against the running interpreter, and offers
no `--python-version` override).

Exit codes:
    0  every lock matches its source
    1  a lock has drifted (the message names the offending packages)
    2  the check could not run (missing pip-tools, wrong Python, ...)
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

# (source, compiled lock) pairs. Only the lambda bundles are guarded:
# `requirements-dev.txt` holds dev tooling rather than a deployable
# bundle, and it is compiled with a different Python, so its marker set
# is not what this check is about.
LOCKS = (
    (
        REPO_ROOT / "lambda" / "requirements-aws.in",
        REPO_ROOT / "lambda" / "requirements-aws.txt",
    ),
    (
        REPO_ROOT / "lambda" / "requirements-alicloud.in",
        REPO_ROOT / "lambda" / "requirements-alicloud.txt",
    ),
)

# `name==version` at the start of a line. The lock writes the version
# followed by ` \` and then indented `--hash=` lines, so the version is
# terminated by whitespace, a backslash, or end of line.
PIN_RE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s\\]+)")

# pip-compile stamps the interpreter it compiled with into the header.
HEADER_PYTHON_RE = re.compile(r"autogenerated by pip-compile with Python (\d+)\.(\d+)")


def normalize(name: str) -> str:
    """PEP 503 normalisation: case-insensitive, and `_` == `-`."""
    return name.lower().replace("_", "-")


def parse_pins(text: str) -> dict[str, str]:
    """Return {normalised name: version} for every `name==version` pin."""
    pins: dict[str, str] = {}
    for line in text.splitlines():
        match = PIN_RE.match(line)
        if match:
            pins[normalize(match.group(1))] = match.group(2)
    return pins


def target_python(text: str) -> tuple[int, int] | None:
    """Return the (major, minor) Python the lock was compiled for."""
    match = HEADER_PYTHON_RE.search(text)
    if not match:
        return None
    return (int(match.group(1)), int(match.group(2)))


def resolve(source: Path, lock: Path) -> dict[str, str]:
    """Re-resolve `source` with pip-compile, reusing `lock`'s existing pins.

    The lock is copied to a temporary file and handed to pip-compile as
    the output file: pip-compile treats the pins already present there as
    the versions to keep, so the resolution reflects the committed lock
    rather than "latest of everything on PyPI". The copy also means the
    committed lock is never modified.
    """
    with tempfile.TemporaryDirectory() as tmpdir:
        tmp_lock = Path(tmpdir) / lock.name
        shutil.copyfile(lock, tmp_lock)
        result = subprocess.run(
            [
                sys.executable,
                "-m",
                "piptools",
                "compile",
                "--quiet",
                "--allow-unsafe",
                f"--output-file={tmp_lock}",
                str(source),
            ],
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode != 0:
            detail = (result.stderr or result.stdout).strip()
            raise RuntimeError(
                f"pip-compile failed for {source.name} (rc={result.returncode}):\n{detail}"
            )
        return parse_pins(tmp_lock.read_text())


def diff_pins(
    committed: dict[str, str], resolved: dict[str, str]
) -> tuple[list[str], list[str], list[str]]:
    """Compare two pin sets.

    Returns (missing, extra, changed):
      missing  — resolved but not committed (the lock dropped a pin)
      extra    — committed but not resolved (the lock kept a stale pin)
      changed  — present in both, pinned to different versions
    """
    missing = sorted(k for k in resolved if k not in committed)
    extra = sorted(k for k in committed if k not in resolved)
    changed = sorted(
        k for k in committed.keys() & resolved.keys() if committed[k] != resolved[k]
    )
    return missing, extra, changed


def report(lock: Path, source: Path, committed: dict, resolved: dict) -> None:
    """Print the drift between the committed lock and the resolution."""
    missing, extra, changed = diff_pins(committed, resolved)

    print(
        f"FAIL: {lock.relative_to(REPO_ROOT)} has drifted from its source.",
        file=sys.stderr,
    )
    print(f"      source: {source.relative_to(REPO_ROOT)}", file=sys.stderr)
    for label, names in (
        ("missing from the lock", missing),
        ("not in the resolved graph", extra),
        ("pinned to a different version", changed),
    ):
        if names:
            print(f"      {label}: {', '.join(names)}", file=sys.stderr)
    print(
        "      Fix: run `mise run lock` and commit the regenerated lock.",
        file=sys.stderr,
    )


def main() -> int:
    for source, lock in LOCKS:
        if not source.exists() or not lock.exists():
            print(
                f"FATAL: expected {source.relative_to(REPO_ROOT)} and "
                f"{lock.relative_to(REPO_ROOT)} to exist.",
                file=sys.stderr,
            )
            return 2

        text = lock.read_text()
        target = target_python(text)
        if target is None:
            print(
                f"FATAL: {lock.relative_to(REPO_ROOT)} has no pip-compile header, "
                "so its target Python cannot be determined.",
                file=sys.stderr,
            )
            return 2

        running = (sys.version_info[0], sys.version_info[1])
        if target != running:
            print(
                f"FATAL: {lock.relative_to(REPO_ROOT)} was compiled for Python "
                f"{target[0]}.{target[1]}, but this check is running under Python "
                f"{running[0]}.{running[1]}. pip-compile evaluates environment "
                "markers against the running interpreter, so re-run the check "
                "with the interpreter the lock targets.",
                file=sys.stderr,
            )
            return 2

        committed = parse_pins(text)
        try:
            resolved = resolve(source, lock)
        except RuntimeError as exc:
            print(f"FATAL: {exc}", file=sys.stderr)
            return 2

        if committed != resolved:
            report(lock, source, committed, resolved)
            return 1

        print(
            f"OK: {lock.relative_to(REPO_ROOT)} matches the resolution of "
            f"{source.relative_to(REPO_ROOT)} "
            f"({len(committed)} packages, Python {target[0]}.{target[1]})."
        )

    return 0


if __name__ == "__main__":
    sys.exit(main())
